// Generates src/poster-fonts.css: the two poster faces embedded as data URLs
// (font-display: block, so the poster never flashes a fallback face).
// "Orbit Sans" = Geist 400, "Orbit Display" = Instrument Serif 400 (both OFL-1.1).
import { readFile, writeFile } from "node:fs/promises";

const faces = [
  ["Orbit Sans", "node_modules/@fontsource/geist-sans/files/geist-sans-latin-400-normal.woff2"],
  ["Orbit Display", "node_modules/@fontsource/instrument-serif/files/instrument-serif-latin-400-normal.woff2"],
];

let css = "/* Generated by scripts/embed-poster-fonts.mjs: do not edit by hand. */\n";
for (const [family, file] of faces) {
  const b64 = (await readFile(file)).toString("base64");
  css += `@font-face {\n  font-family: "${family}";\n  font-style: normal;\n  font-weight: 400;\n  font-display: block;\n  src: url(data:font/woff2;base64,${b64}) format("woff2");\n}\n`;
}
await writeFile("src/poster-fonts.css", css);
console.log("wrote src/poster-fonts.css", css.length, "bytes");
